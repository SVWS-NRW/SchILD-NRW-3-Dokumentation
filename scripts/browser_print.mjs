import { siteBase } from '../.vitepress/site-base.mjs'
const base = 'http://127.0.0.1:4189' + siteBase.slice(0, -1)
import assert from 'node:assert/strict'

export async function checkPrintLayout(page) {
  await page.goto(base + '/administration/datenbanken/schild-nrw-daten-in-eine-andere-datenbank-uebertragen-migrieren-tutorial.html', { waitUntil: 'networkidle' })
  const details = page.locator('.vp-doc details').first()
  assert.equal(await details.getAttribute('open'), null)
  const imageLoading = await page.locator('.vp-doc img').evaluateAll(images => images.map(image => image.getAttribute('loading')))
  const dark = await page.evaluate(() => document.documentElement.classList.contains('dark'))
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  await page.emulateMedia({ media: 'print' })
  await page.waitForFunction(() => document.querySelector('.vp-doc details')?.open)
  assert.equal(await page.locator('.print-source').count(), 1)
  assert(await page.locator('.VPNav').evaluate(element => getComputedStyle(element).display === 'none'))
  assert(await page.locator('.vp-doc').evaluate(element => getComputedStyle(element).color === 'rgb(17, 17, 17)'))
  await page.locator('.vp-doc img').evaluateAll(images => Promise.all(images.map(image => image.decode())))
  const pdf = await page.pdf({ preferCSSPageSize: true, printBackground: true })
  assert(pdf.length > 10000)
  await page.emulateMedia({ media: 'screen' })
  await page.locator('.print-source').waitFor({ state: 'detached' })
  assert.equal(await details.getAttribute('open'), null)
  assert.equal(await page.locator('.print-source').count(), 0)
  assert.deepEqual(await page.locator('.vp-doc img').evaluateAll(images => images.map(image => image.getAttribute('loading'))), imageLoading)
  await details.evaluate(element => { element.open = true })
  await page.evaluate(() => { window.dispatchEvent(new Event('beforeprint')); window.dispatchEvent(new Event('beforeprint')) })
  assert.equal(await page.locator('.print-source').count(), 1)
  await page.evaluate(() => window.dispatchEvent(new Event('afterprint')))
  assert(await details.evaluate(element => element.open))
  await details.evaluate(element => { element.open = false })
  await page.evaluate(value => document.documentElement.classList.toggle('dark', value), dark)

  await page.goto(base + '/administration/datenbanken/migrationshintergrund-automatisch-setzen-gruppenprozesse-allgemein.html', { waitUntil: 'networkidle' })
  await page.emulateMedia({ media: 'print' })
  await page.locator('.print-media-link').waitFor()
  assert.equal(await page.locator('.print-media-link a').getAttribute('href'), 'https://www.youtube.com/watch?v=8mvm87KEehE')
  assert(await page.locator('.vp-doc iframe').evaluate(element => getComputedStyle(element).display === 'none'))
  await page.emulateMedia({ media: 'screen' })
  await page.locator('.print-media-link').waitFor({ state: 'detached' })
  assert.equal(await page.locator('.print-media-link').count(), 0)

  await page.goto(base + '/schild3/import-export-statistik/schnittstellenbeschreibung.html', { waitUntil: 'networkidle' })
  await page.emulateMedia({ media: 'print' })
  assert(await page.locator('.interface-table-scroll').first().evaluate(element => getComputedStyle(element).overflowX === 'visible'))
  assert(await page.locator('.interface-fields').evaluateAll(tables => tables.every(table => table.scrollWidth <= table.clientWidth + 2)))
  assert(await page.locator('.interface-fields thead').first().evaluate(element => getComputedStyle(element).display === 'table-header-group'))
  await page.emulateMedia({ media: 'screen' })
}
